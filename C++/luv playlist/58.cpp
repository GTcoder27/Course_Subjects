#include<bits/stdc++.h>
using namespace std;
// << -> left shift
// >> -> right shift

int main()
{
    cout<<INT_MAX<<endl;
    int a = 2<<1;
    cout<<a<<endl;
    int b = 2>>1;
    cout<<b<<endl;
    int c = (1LL<<31) - 1;
    cout<<c<<endl;
    unsigned int d = (1LL<<32) - 1;
    cout<<d<<endl;


    


    return 0;
}